function icGetLang(){
  return localStorage.getItem('ic_lang') || 'RU';
}

function icSetLang(lang){
  const isStaged = I18N_STAGED.includes(lang);
  if(!isStaged){
    localStorage.setItem('ic_lang', lang);
  }
  const activeLang = I18N[localStorage.getItem('ic_lang')] ? localStorage.getItem('ic_lang') : 'RU';
  localStorage.setItem('ic_lang', activeLang); // normalize, in case nothing was ever set
  localStorage.setItem('ic_display_lang', lang); // which pill looks active
  icApplyLang();
  if(isStaged){
    icToast(I18N[activeLang]['toast.stagedLang']);
  }
}

function icApplyLang(){
  const activeLabel = localStorage.getItem('ic_display_lang') || 'RU';
  const dict = I18N[localStorage.getItem('ic_lang')] || I18N.RU;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if(dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if(dict[key]) el.setAttribute('placeholder', dict[key]);
  });
  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === activeLabel);
  });
  const langCode = localStorage.getItem('ic_lang');
  document.documentElement.lang = langCode === 'EN' ? 'en' : (langCode === 'KZ' ? 'kk' : 'ru');
  document.dispatchEvent(new CustomEvent('ic:langchange'));
}

function icT(key){
  const dict = I18N[localStorage.getItem('ic_lang')] || I18N.RU;
  return dict[key] || key;
}
